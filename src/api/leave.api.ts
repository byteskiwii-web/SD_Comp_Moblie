import { apiClient } from './client';

// Top level, alongside /regularisation. Leave is its own resource on the
// server; the app presents it as its own tab.
const BASE = '/leave';

/**
 * paid / unpaid -- ordinary leave, the distinction payroll acts on.
 * comp-off      -- spends comp off already earned; the server refuses more
 *                  than is left (COMP_OFF_INSUFFICIENT).
 * week-off      -- the weekly off: one full weekday (Monday-Friday), one per
 *                  week, decided by a manager like leave. Weekends are
 *                  working days at the stores.
 */
export type LeaveType = 'paid' | 'unpaid' | 'comp-off' | 'week-off';
export type LeaveStatus = 'pending' | 'approved' | 'rejected' | 'cancelled';

export const LEAVE_TYPES: LeaveType[] = ['paid', 'unpaid', 'comp-off', 'week-off'];

/**
 * What can be applied for. Paid leave is retired (old requests still show);
 * 'week-off' here MOVES the weekly off, which is otherwise automatic.
 */
export const APPLY_TYPES: LeaveType[] = ['unpaid', 'comp-off', 'week-off'];

/** A week-off change: that week only, or from that week onwards. */
export type WeekOffScope = 'week' | 'permanent';

/** ISO weekdays a week off may fall on (1 = Monday). Mirrors LEAVE_WEEK_OFF_DAYS on the server. */
export const WEEK_OFF_DAYS = [1, 2, 3, 4, 5];

/**
 * Catalogue KEYS rather than English.
 *
 * These sat here as finished strings, which read as part of the wire contract
 * when they are really display text. A key keeps the mapping next to the type
 * it describes while leaving the WORDS to the language layer -- and a
 * module-level constant holding text would freeze whichever language loaded
 * first, which is the bug this avoids.
 */
export const LEAVE_TYPE_LABEL_KEY = {
  paid: 'leaveType.paid',
  unpaid: 'leaveType.unpaid',
  'comp-off': 'leaveType.compOff',
  'week-off': 'leaveType.weekOff',
} as const;

/** What each one means for the day, said plainly on the form. */
export const LEAVE_TYPE_HINT_KEY = {
  paid: 'leaveType.paidHint',
  unpaid: 'leaveType.unpaidHint',
  'comp-off': 'leaveType.compOffHint',
  'week-off': 'leaveType.weekOffHint',
} as const;

export type LeaveRequest = {
  id: string;
  employeeId: string;
  employeeName?: string;
  storeCode: string;
  storeName?: string | null;
  leaveType: LeaveType;
  startDate: string;
  endDate: string;
  halfDay: boolean;
  /** Calendar days, generated by the database. `0.5` for a half day. */
  totalDays: number | null;
  /** What it costs: its days less the weekly offs and national holidays in it. */
  workingDays?: number | null;
  /** Week-off changes only: that week, or from that week on. */
  weekOffScope?: WeekOffScope | null;
  reason: string;
  status: LeaveStatus;
  createdAt: string;
  /** Retired: an unpaid day once claimed as worked, and what it earned back. */
  workedOn: string | null;
  compOffEarned: number;
  compOffUsedAt: string | null;
  decidedAt: string | null;
  decidedBy: string | null;
  decisionNote: string | null;
};

export type NewLeave = {
  leave_type: LeaveType;
  start_date: string;
  end_date: string;
  half_day?: boolean;
  reason: string;
  week_off_scope?: WeekOffScope;
};

/**
 * Leave taken in ONE MONTH, plus the eleven before it.
 *
 * Monthly because that is how leave is discussed and approved -- an annual
 * running total answers "how many days in August" only by subtraction.
 * `compOffOutstanding` is counted apart from days taken: it is leave OWED, and
 * folding it in would make somebody who came in look like somebody who did not.
 */
export type LeaveMonth = {
  month: string;
  taken: Record<LeaveType, number>;
  pending: Record<LeaveType, number>;
  takenTotal: number;
  pendingTotal: number;
  /** Approved week offs in the month -- not part of takenTotal. */
  weekOffsTaken?: number;
};

export type LeaveSummary = LeaveMonth & {
  employeeId: string;
  compOffEarned: number;
  /** Comp off already taken (approved comp-off leave). */
  compOffUsed?: number;
  /** Comp off reserved by requests still waiting for a decision. */
  compOffPending?: number;
  /** What a new comp-off request may take: earned, less used and pending. */
  compOffOutstanding: number;
  /**
   * National holidays (Republic Day, Independence Day, Gandhi Jayanti) the
   * employee clocked in on -- each earns one comp off, already included in
   * the two totals above. Newest first. Absent from servers before 29 Sep 2026.
   */
  compOffHolidays?: { date: string; name: string }[];
  /** Every comp-off credit, newest first: what is left and when it lapses. */
  compOffCredits?: { date: string; amount: number; remaining: number; expiresOn: string; expired: boolean; holidayName: string | null }[];
  /** Credits with some left that lapse within the notice window. */
  compOffExpiringSoon?: { date: string; remaining: number; expiresOn: string }[];
  /** How long comp off lasts from the day worked (60). */
  compOffValidDays?: number;
  /** The fixed weekly off in force today, ISO weekday (1 = Monday), or null. */
  weekOffDay?: number | null;
  byMonth: LeaveMonth[];
};

/**
 * A reviewer gets their scoped queue here; everyone else gets their own
 * applications. The employee app is always the second case.
 *
 * The shared list envelope: `data` is the array, paging rides in `meta`.
 * Pending first, then start date newest first — already the order the screen
 * wants, but it is re-sorted client-side anyway so a server change cannot
 * quietly reorder the list.
 */
/**
 * The team's leave, for a lead looking at their own people.
 *
 * Same `GET /leave` the employee's own list uses -- the server decides who is
 * in scope from the caller's principal, and pins a site-scoped one to their
 * own store whatever is asked for. So there is no employee filter here to get
 * wrong, and a transfer needs no change in the app.
 *
 * A window rather than everything: leave is read to answer "who is off around
 * now", and a year of history makes that harder to see, not easier.
 */
export async function getTeamLeave(from: string, to: string, limit = 100) {
  const res = await apiClient.get<{ success: true; data: LeaveRequest[] }>(BASE, {
    params: { from, to, limit },
  });
  return res.data.data ?? [];
}

/*
 * ASK FOR YOUR OWN, DO NOT ASSUME THE SERVER MEANS YOURS.
 *
 * GET /leave and GET /regularisation scope by LEVEL, not by caller. A field
 * employee resolves to SELF and gets only their own rows, so this read looked
 * correct -- but a team lead resolves to SITE, and the same
 * request returns the WHOLE STORE. Their own "My requests" list was therefore
 * everybody's, with a Withdraw button on each one.
 *
 * Nothing could be damaged: cancel() matches on employee_id = actor.id, so
 * withdrawing a colleague's request would have 404'd. But the list was still
 * showing one person the private reasons another gave for asking for a day
 * off, on a screen that says "My requests".
 *
 * Naming the employee removes the ambiguity entirely: this call means mine at
 * every level, and the team-facing screens keep their own unfiltered calls
 * where seeing everybody is the point.
 */
export async function getMyLeave(employeeId: string, limit = 50) {
  const res = await apiClient.get<{ success: true; data: LeaveRequest[] }>(BASE, {
    params: { limit, employee_id: employeeId },
  });
  return res.data.data ?? [];
}

/** `month` is YYYY-MM. Omitted means the current one. */
export async function getLeaveSummary(month?: string) {
  const res = await apiClient.get<{ success: true; data: LeaveSummary }>(`${BASE}/summary`, {
    params: month ? { month } : undefined,
  });
  return res.data.data;
}

export async function applyForLeave(input: NewLeave) {
  const res = await apiClient.post<{ success: true; data: LeaveRequest }>(BASE, input);
  return res.data.data;
}

/** Withdraw one's own request. Only works while it is still pending. */
export async function cancelLeave(id: string) {
  const res = await apiClient.post<{ success: true; data: LeaveRequest }>(`${BASE}/${id}/cancel`, {});
  return res.data.data;
}
